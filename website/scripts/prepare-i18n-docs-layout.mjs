/**
 * 国际站（默认 en）：docs 在 /docs，中文在 i18n/zh-Hans；清空 i18n/en/.../doc 避免覆盖默认英文。
 * 国内站（DOMESTIC_SITE + 默认 zh-Hans）：中文在 /docs（插件 path 指向 zh i18n），英文拷贝到 i18n/en/.../doc。
 * 同时写入 static/_redirects：国际站 301 去掉旧 /en 前缀；国内站不 strip /en。
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");

const EN_DOC_DIR = path.join(
  root,
  "i18n/en/docusaurus-plugin-content-docs/current/doc",
);
const EN_BLOG_DIR = path.join(
  root,
  "i18n/en/docusaurus-plugin-content-blog",
);
const SRC_EN_DOCS = path.join(root, "docs/doc");
const SRC_EN_BLOG = path.join(root, "blog");
const ZH_BLOG_DIR = path.join(
  root,
  "i18n/zh-Hans/docusaurus-plugin-content-blog",
);
const REDIRECTS_PATH = path.join(root, "static/_redirects");
const ROBOTS_PATH = path.join(root, "static/robots.txt");

const REDIRECTS_INTERNATIONAL = `# Auto-generated by scripts/prepare-i18n-docs-layout.mjs (default locale: en)
/en   /   301
/en/  /   301
/en/* /:splat  301
`;

const REDIRECTS_DOMESTIC = `# Auto-generated by scripts/prepare-i18n-docs-layout.mjs (default locale: zh-Hans; English under /en/)
`;

const ROBOTS_INTERNATIONAL = `User-agent: *
Allow: /

Sitemap: https://etedrop.com/sitemap.xml
`;

const ROBOTS_DOMESTIC = `User-agent: *
Allow: /

Sitemap: https://etedrop.cn/sitemap.xml
`;

function clearEnDocOverrides() {
  if (!fs.existsSync(EN_DOC_DIR)) {
    fs.mkdirSync(EN_DOC_DIR, { recursive: true });
    return;
  }
  for (const name of fs.readdirSync(EN_DOC_DIR)) {
    fs.rmSync(path.join(EN_DOC_DIR, name), { recursive: true, force: true });
  }
}

function copyEnDocsForDomestic() {
  if (!fs.existsSync(SRC_EN_DOCS)) {
    console.error("[prepare-i18n-docs-layout] Missing", SRC_EN_DOCS);
    process.exit(1);
  }
  clearEnDocOverrides();
  for (const name of fs.readdirSync(SRC_EN_DOCS)) {
    fs.cpSync(
      path.join(SRC_EN_DOCS, name),
      path.join(EN_DOC_DIR, name),
      { recursive: true },
    );
  }
}

function clearEnBlogOverrides() {
  if (!fs.existsSync(EN_BLOG_DIR)) {
    fs.mkdirSync(EN_BLOG_DIR, { recursive: true });
    return;
  }
  for (const name of fs.readdirSync(EN_BLOG_DIR)) {
    if (name === "options.json") continue;
    fs.rmSync(path.join(EN_BLOG_DIR, name), { recursive: true, force: true });
  }
}

function copyEnBlogForDomestic() {
  if (!fs.existsSync(SRC_EN_BLOG)) return;
  clearEnBlogOverrides();
  for (const name of fs.readdirSync(SRC_EN_BLOG)) {
    fs.cpSync(
      path.join(SRC_EN_BLOG, name),
      path.join(EN_BLOG_DIR, name),
      { recursive: true },
    );
  }
}

/** 国内站默认 blog 在 zh-Hans 目录，需同步 authors.yml（及 tags.yml 若存在） */
function syncZhBlogDataFiles() {
  if (!fs.existsSync(SRC_EN_BLOG)) return;
  fs.mkdirSync(ZH_BLOG_DIR, { recursive: true });
  for (const name of ["authors.yml", "tags.yml"]) {
    const src = path.join(SRC_EN_BLOG, name);
    if (fs.existsSync(src)) {
      fs.cpSync(src, path.join(ZH_BLOG_DIR, name));
    }
  }
}

const mode = process.argv[2] ?? "international";

if (mode !== "international" && mode !== "domestic") {
  console.error(
    "Usage: node scripts/prepare-i18n-docs-layout.mjs [international|domestic]",
  );
  process.exit(1);
}

if (mode === "domestic") {
  copyEnDocsForDomestic();
  copyEnBlogForDomestic();
  syncZhBlogDataFiles();
  fs.writeFileSync(REDIRECTS_PATH, REDIRECTS_DOMESTIC, "utf8");
  fs.writeFileSync(ROBOTS_PATH, ROBOTS_DOMESTIC, "utf8");
} else {
  clearEnDocOverrides();
  clearEnBlogOverrides();
  fs.writeFileSync(REDIRECTS_PATH, REDIRECTS_INTERNATIONAL, "utf8");
  fs.writeFileSync(ROBOTS_PATH, ROBOTS_INTERNATIONAL, "utf8");
}

console.log(`[prepare-i18n-docs-layout] ${mode}`);
